export const SKILL_NAMES_BY_CLASS: Record<string, string[]> = {
  Amazon: AMAZON,
  Sorceress: SORCERESS,
  Necromancer: NECROMANCER,
  Paladin: PALADIN,
  Barbarian: BARBARIAN,
  Druid: DRUID,
  Assassin: ASSASSIN,
  Warlock: WARLOCK,
}

export function skillName(class_en: string, skillId: number): string {
  const names = SKILL_NAMES_BY_CLASS[class_en]
  if (names && skillId >= 0 && skillId < names.length) {
    return names[skillId]
  }
  return `#${skillId}`
}
