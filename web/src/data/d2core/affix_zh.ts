/** 取词缀名称中文（有翻译则返回,否则返回英文原文） */
export function affixNameZh(nameEn: string): string {
  // 先查前缀
  if (PREFIX_NAME_ZH[nameEn]) return PREFIX_NAME_ZH[nameEn]
  // 再查后缀
  if (SUFFIX_NAME_ZH[nameEn]) return SUFFIX_NAME_ZH[nameEn]
  return nameEn
}

/** 取词缀显示名，格式：中文(English) — 有翻译则显示中文+原文，无翻译则仅显示原文 */
export function affixNameDisplay(nameEn: string): { display: string; zh: string; en: string; hasZh: boolean } {
  const zh = affixNameZh(nameEn)
  const hasZh = zh !== nameEn
  return {
    display: hasZh ? `${zh}(${nameEn})` : nameEn,
    zh,
    en: nameEn,
    hasZh,
  }
}

/** 取物品类型中文,无匹配时返回原代码 */
export function itypeZh(code: string): string {
  return ITYPE_ZH[code] ?? code
}

/** 取属性代码中文描述,无匹配时返回原代码 */
export function modCodeZh(code: string): string {
  return MOD_CODE_ZH[code] ?? code
}
