/// Look up base stats for a weapon or armor by item code.
/// Returns `(min_damage_or_def, max_damage_or_def, ...)` or None.

/// Weapon base data.
#[derive(Debug, Clone, Copy, Default)]
pub struct WeaponStats {
    pub mindam: u16,
    pub maxdam: u16,
    pub twohand_mindam: u16,
    pub twohand_maxdam: u16,
    pub reqstr: u8,
    pub reqdex: u8,
    pub level: u8,
    pub levelreq: u8,
    pub durability: u16,
    pub is_two_handed: bool,
}

impl WeaponStats {
    /// 显示用伤害区间: 双手武器取 twohand, 单手取 mindam/maxdam。
    pub fn display_damage(&self) -> (u16, u16) {
        if self.is_two_handed {
            (self.twohand_mindam, self.twohand_maxdam)
        } else {
            (self.mindam, self.maxdam)
        }
    }
}

/// Armor base data.
#[derive(Debug, Clone, Copy, Default)]
pub struct ArmorStats {
    pub minac: u16,
    pub maxac: u16,
    pub reqstr: u8,
    pub reqdex: u8,
    pub level: u8,
    pub levelreq: u8,
    pub durability: u16,
}

/// Lookup weapon base stats by item code (3-char).
pub fn weapon_stats(code: &str) -> Option<WeaponStats> {
    let code = if code.len() == 4 { &code[1..] } else { code };
    WEAPON_BASE.iter().find(|(k, _)| *k == code).map(|(_, v)| {
        let (md, xd, h2md, h2xd, rs, rd, lv, lvr, dur, is2h) = *v;
        WeaponStats {
            mindam: md, maxdam: xd,
            twohand_mindam: h2md, twohand_maxdam: h2xd,
            reqstr: rs, reqdex: rd,
            level: lv, levelreq: lvr,
            durability: dur, is_two_handed: is2h,
        }
    })
}

/// Lookup armor base stats by item code (3-char).
pub fn armor_stats(code: &str) -> Option<ArmorStats> {
    let code = if code.len() == 4 { &code[1..] } else { code };
    ARMOR_BASE.iter().find(|(k, _)| *k == code).map(|(_, v)| {
        let (mn, mx, rs, rd, lv, lvr, dur) = *v;
        ArmorStats {
            minac: mn, maxac: mx,
            reqstr: rs, reqdex: rd,
            level: lv, levelreq: lvr,
            durability: dur,
        }
    })
}

/// Check if a code is armor (has entry in ARMOR_BASE).
pub fn is_armor(code: &str) -> bool {
    armor_stats(code).is_some()
}

/// Check if a code is weapon (has entry in WEAPON_BASE).
pub fn is_weapon(code: &str) -> bool {
    weapon_stats(code).is_some()
}
