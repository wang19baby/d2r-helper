const DEFAULT_WAREHOUSE_PAGE: &str = "默认收藏";

/// Simplified warehouse item for frontend display
#[derive(Debug, Serialize, Deserialize)]
pub struct WarehouseItemResult {
    pub id: String,
    pub item_code: String,
    pub item_name: String,
    pub item_kind: String,
    pub quality: Option<String>,
    pub quantity: u32,
    pub page_name: String,
    pub imported_at: String,
    pub tags: String,
    pub notes: String,
    /// Inventory footprint width (cells). Frontend uses this to render the drag
    /// preview and the placement validator; without it `width × scaledCell` is
    /// `NaN` and the CSS layout collapses.
    pub inv_width: i32,
    /// Inventory footprint height (cells). See `inv_width` for rationale.
    pub inv_height: i32,
    /// Tooltip lines for hover/display, generated by TooltipFormatter::stash_tooltip.
    /// Empty when tooltip data is unavailable (old fallback path).
    pub tooltip_lines: Vec<String>,
    /// 结构化 tooltip 数据（与角色页 build_tooltip_from_stats 同款分类：
    /// 白字基础/蓝字词缀/符文/套装分色 + 镶嵌区块）。
    /// 前端优先消费此字段, None 时降级到 tooltip_lines。
    pub tooltip: Option<crate::commands::character::TooltipData>,
}

/// Default-page lookup result for an item. Returned by `warehouse_resolve_default`.
/// `effective` is the resolved fallback chain result — useful for the frontend
/// to render "当前默认页: X" without doing two round trips.
#[derive(Debug, Serialize, Deserialize)]
pub struct DefaultPageInfo {
    pub item_code: String,
    pub code_default: Option<String>,
    pub item_default: Option<String>,
    pub effective: Option<String>,
}

fn localize_warehouse_items(
    db: &crate::database::Database,
    items: Vec<WarehousedItem>,
) -> Vec<WarehouseItemResult> {
    let language = db
        .get_config("language")
        .ok()
        .flatten()
        .unwrap_or_else(|| "enUS".to_string());
    let profile_id = crate::commands::config::get_active_profile_id(db).unwrap_or(0);
    let conn_ref = db.get_connection();

    if profile_id > 0 {
        let resolver = crate::resource::get_cached_resolver(conn_ref, profile_id);
        let quality_u8 = |q: &Option<String>| -> Option<u8> {
            match q.as_deref() {
                Some("unique") => Some(7),
                Some("rare") => Some(6),
                Some("set") => Some(5),
                Some("magic") => Some(4),
                Some("superior") => Some(3),
                Some("low") => Some(1),
                _ => None,
            }
        };
        items
            .into_iter()
            .map(|i| {
                let mut resolved = resolver.resolve(conn_ref, &i.item_code, None, None, None, &language);
                // 符文之语名字: 从 item_json 的 socketed_items 匹配 runeword,
                // 与角色页 build_stored_item_summary 一致 (底材名[精神])
                let socketed: Vec<crate::protocol::common::Item> = serde_json::from_str::<serde_json::Value>(&i.item_json)
                    .ok()
                    .and_then(|j| j.get("socketed_items").cloned())
                    .and_then(|v| serde_json::from_value(v).ok())
                    .unwrap_or_default();
                let runes: Vec<&str> = socketed.iter().map(|s| s.code.as_str()).collect();
                if !runes.is_empty()
                    && let Some(rw_en) = crate::data::runewords::match_runeword(&runes) {
                    if language == "enUS" {
                        resolved.display_name = format!("{} [{}]", resolved.display_name, rw_en);
                    } else if let Some(rw_zh) = crate::data::runewords::match_runeword_zh(&runes) {
                        resolved.display_name = format!("{}[{}]", resolved.display_name, rw_zh);
                    } else {
                        resolved.display_name = format!("{} [{}]", resolved.display_name, rw_en);
                    }
                }
                // Parse stat_lists from item_json (stored during deposit)
                let stat_lists: Vec<crate::protocol::common::stat_list::StatList> = serde_json::from_str::<serde_json::Value>(&i.item_json)
                    .ok()
                    .and_then(|j| j.get("stat_lists").cloned())
                    .and_then(|sl| serde_json::from_value(sl).ok())
                    .unwrap_or_default();
                let stats: Vec<crate::protocol::common::ItemStat> =
                    stat_lists.iter().flat_map(|sl| sl.stats.iter().cloned()).collect();
                let tooltip_lines = crate::resource::TooltipFormatter::stash_tooltip(
                    &resolved.display_name,
                    &resolved.name_en,
                    &i.item_code,
                    &i.item_kind,
                    quality_u8(&i.quality),
                    i.quantity,
                    &language,
                    &stats,
                );
                // 结构化 tooltip: 与角色页 build_tooltip_from_stats 同款分类
                // (白字基础/蓝字词缀/符文/套装分色 + 镶嵌区块), 收藏页 hover 与角色页一致
                let quality_byte = quality_u8(&i.quality);
                let stats_cat = crate::commands::character::categorize_item_stats(
                    quality_byte.unwrap_or(2),
                    !runes.is_empty(),
                    &stat_lists,
                );
                let mut tooltip = crate::commands::character::build_tooltip_from_stats(
                    &stats_cat, &language, Some(conn_ref), profile_id,
                );
                // 底材基础行 (对齐角色页 build_stored_item_summary)
                // 实际防御优先: item_json 存的实际 defense;0/缺失时回退底材区间
                let stored_defense: u16 = serde_json::from_str::<serde_json::Value>(&i.item_json)
                    .ok()
                    .and_then(|j| j.get("defense").cloned())
                    .and_then(|v| v.as_u64().map(|n| n as u16))
                    .unwrap_or(0);
                if let Some(def) = crate::data::items_base::armor_stats(&i.item_code) {
                    if stored_defense > 0 {
                        tooltip.base_stats.insert(0, format!("防御: {}", stored_defense));
                    } else if def.minac > 0 || def.maxac > 0 {
                        tooltip.base_stats.insert(0, format!("防御: {}-{}", def.minac, def.maxac));
                    }
                    if def.levelreq > 0 { tooltip.base_stats.push(format!("需要等级: {}", def.levelreq)); }
                    if def.reqstr > 0 { tooltip.base_stats.push(format!("需要力量: {}", def.reqstr)); }
                    if def.reqdex > 0 { tooltip.base_stats.push(format!("需要敏捷: {}", def.reqdex)); }
                }
                // 盾牌 smite 伤害 (含圣骑士盾)
                if let Some((smin, smax)) = crate::data::items_base::shield_smite(&i.item_code) {
                    tooltip.base_stats.push(if smin == smax {
                        format!("盾击伤害: {}", smin)
                    } else {
                        format!("盾击伤害: {}-{}", smin, smax)
                    });
                }
                if let Some(wpn) = crate::data::items_base::weapon_stats(&i.item_code) {
                    let (dmin, dmax) = wpn.display_damage();
                    if dmin > 0 || dmax > 0 {
                        tooltip.base_stats.push(if dmin == dmax {
                            format!("攻击力: {}", dmin)
                        } else {
                            format!("攻击力: {}-{}", dmin, dmax)
                        });
                    }
                    if wpn.levelreq > 0 { tooltip.base_stats.push(format!("需要等级: {}", wpn.levelreq)); }
                    if wpn.reqstr > 0 { tooltip.base_stats.push(format!("需要力量: {}", wpn.reqstr)); }
                    if wpn.reqdex > 0 { tooltip.base_stats.push(format!("需要敏捷: {}", wpn.reqdex)); }
                }
                // 孔位 + 镶嵌 (对齐角色页)
                if !socketed.is_empty() {
                    tooltip.sockets = Some(crate::commands::character::SocketsInfo {
                        count: socketed.len() as u8,
                        items: socketed.iter().map(|s| crate::commands::character::SocketedItemInfo {
                            code: s.code.clone(),
                            name_zh: None,
                            name_en: None,
                            quality: Some(s.quality.as_u8()).filter(|&q| (2..=8).contains(&q)),
                            amount: s.amount,
                        }).collect(),
                    });
                }
                WarehouseItemResult {
                    id: i.id,
                    item_code: i.item_code,
                    item_name: resolved.display_name,
                    item_kind: i.item_kind,
                    quality: i.quality,
                    quantity: i.quantity,
                    page_name: i.page_name,
                    imported_at: i.imported_at,
                    tags: i.tags,
                    notes: i.notes,
                    inv_width: i.inv_width,
                    inv_height: i.inv_height,
                    tooltip_lines,
                    tooltip: Some(tooltip),
                }
            })
            .collect()
    } else {
        items
            .into_iter()
            .map(|i| {
                let code = i.item_code.clone();
                let tooltip_lines = crate::resource::TooltipFormatter::stash_tooltip(
                    &code, &code, &code, &i.item_kind,
                    None, i.quantity, &language, &[],
                );
                WarehouseItemResult {
                    id: i.id,
                    item_code: code,
                    item_name: i.item_code,
                    item_kind: i.item_kind,
                    quality: i.quality,
                    quantity: i.quantity,
                    page_name: i.page_name,
                    imported_at: i.imported_at,
                    tags: i.tags,
                    notes: i.notes,
                    inv_width: i.inv_width,
                    inv_height: i.inv_height,
                    tooltip_lines,
                    tooltip: None,
                }
            })
            .collect()
    }
}

fn validate_page_name(input: &str) -> Result<String, String> {
    let name = input.trim();
    if name.is_empty() {
        return Err("收藏页名称不能为空".to_string());
    }
    if name.chars().count() > 64 {
        return Err("收藏页名称不能超过 64 个字符".to_string());
    }
    if name.chars().any(|ch| ch.is_control()) {
        return Err("收藏页名称不能包含控制字符".to_string());
    }
    Ok(name.to_string())
}

/// List all warehoused items (with localized names)
#[tauri::command]
pub fn warehouse_list(state: State<AppState>) -> Result<Vec<WarehouseItemResult>, String> {
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let active_profile_key = crate::commands::config::get_active_profile_key(&db).unwrap_or_default();
    let items = if !active_profile_key.is_empty() {
        db.warehouse_list_by_profile(&active_profile_key)
            .or_else(|_| db.warehouse_list_all())
            .map_err(|e| e.to_string())?
    } else {
        db.warehouse_list_all().map_err(|e| e.to_string())?
    };
    Ok(localize_warehouse_items(&db, items))
}

