#[tauri::command]
pub fn warehouse_search(
    state: State<AppState>,
    source_character: Option<String>,
    item_kind: Option<String>,
    equipment_slot: Option<String>,
    quality: Option<String>,
    search_text: Option<String>,
    page_name: Option<String>,
    limit: Option<i64>,
    offset: Option<i64>,
) -> Result<Vec<crate::commands::warehouse::WarehouseItemResult>, String> {
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let repos = db.repos();
    let active_profile_key = crate::commands::config::get_active_profile_key(&db).unwrap_or_default();
    let filters = crate::database::repository::warehouse_repo::WarehouseFilters {
        profile_key: (!active_profile_key.is_empty()).then_some(active_profile_key),
        source_character,
        item_kind,
        equipment_slot,
        quality,
        search_text,
        page_name,
        limit,
        offset,
    };
    let items = repos.warehouse.search(&filters).map_err(|e| e.to_string())?;
    // Convert to frontend-friendly format (same as existing warehouse_list paths)
    let result: Vec<crate::commands::warehouse::WarehouseItemResult> = crate::commands::warehouse::localize_warehouse_items(&db, items);
    Ok(result)
}

// ── Default page (per-code + per-item override) ─────────────
//
// Two-layer fallback: per-item override (warehouse_items.override_default_page)
// → per-code default (warehouse_default_pages.page_name). The frontend renders
// the resolved value via `warehouse_resolve_default` and mutates either layer
// with the four *_default commands below. `warehouse_deposit` (above) consults
// `warehouse_get_code_default` when no explicit page_name is supplied.

#[tauri::command]
pub fn warehouse_set_code_default(
    state: State<AppState>,
    item_code: String,
    page_name: String,
) -> Result<(), String> {
    let trimmed_item_code = item_code.trim().to_string();
    if trimmed_item_code.is_empty() {
        return Err("物品 code 不能为空".to_string());
    }
    let validated_page = validate_page_name(&page_name)?;
    let db = state.db.lock().map_err(|e| e.to_string())?;
    db.warehouse_set_code_default(&trimmed_item_code, &validated_page)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn warehouse_clear_code_default(
    state: State<AppState>,
    item_code: String,
) -> Result<bool, String> {
    let trimmed_item_code = item_code.trim().to_string();
    if trimmed_item_code.is_empty() {
        return Err("物品 code 不能为空".to_string());
    }
    let db = state.db.lock().map_err(|e| e.to_string())?;
    db.warehouse_clear_code_default(&trimmed_item_code)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn warehouse_set_item_default(
    state: State<AppState>,
    item_id: String,
    page_name: String,
) -> Result<bool, String> {
    let validated_page = validate_page_name(&page_name)?;
    let db = state.db.lock().map_err(|e| e.to_string())?;
    db.warehouse_set_item_default(&item_id, &validated_page)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn warehouse_clear_item_default(
    state: State<AppState>,
    item_id: String,
) -> Result<bool, String> {
    let db = state.db.lock().map_err(|e| e.to_string())?;
    db.warehouse_clear_item_default(&item_id)
        .map_err(|e| e.to_string())
}

/// Resolve the default page for an item, returning all three layers so the
/// frontend can show "code: 符文页, override: (无), effective: 符文页".
/// `item_id` is optional — stash items don't have one yet, so only the
/// per-code layer applies.
#[tauri::command]
pub fn warehouse_resolve_default(
    state: State<AppState>,
    item_code: String,
    item_id: Option<String>,
) -> Result<DefaultPageInfo, String> {
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let code_default = db
        .warehouse_get_code_default(&item_code)
        .map_err(|e| e.to_string())?;
    let item_default = match item_id.as_deref() {
        Some(id) => db
            .warehouse_get_item_default(id)
            .map_err(|e| e.to_string())?,
        None => None,
    };
    let effective = item_default.as_ref().or(code_default.as_ref()).cloned();
    Ok(DefaultPageInfo {
        item_code,
        code_default,
        item_default,
        effective,
    })
}
