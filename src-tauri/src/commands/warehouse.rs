#[tauri::command]
pub fn warehouse_update_meta(
    state: State<AppState>,
    item_id: String,
    page_name: String,
    tags: String,
    notes: String,
) -> Result<(), String> {
    let validated_page_name = validate_page_name(&page_name)?;
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let active_profile_key = crate::commands::config::get_active_profile_key(&db).unwrap_or_default();
    let updated = if !active_profile_key.is_empty() {
        db.warehouse_update_meta_in_profile(&active_profile_key, &item_id, &validated_page_name, &tags, &notes)
            .or_else(|_| db.warehouse_update_meta(&item_id, &validated_page_name, &tags, &notes))
            .map_err(|e| e.to_string())?
    } else {
        db.warehouse_update_meta(&item_id, &validated_page_name, &tags, &notes)
            .map_err(|e| e.to_string())?
    };
    if !updated {
        return Err("Warehouse item not found in active profile".to_string());
    }
    Ok(())
}

#[tauri::command]
pub fn warehouse_rename_page(
    state: State<AppState>,
    old_page_name: String,
    new_page_name: String,
) -> Result<(), String> {
    if old_page_name.trim() == DEFAULT_WAREHOUSE_PAGE {
        return Err("默认收藏不可重命名".to_string());
    }
    let validated_old_name = validate_page_name(&old_page_name)?;
    let validated_new_name = validate_page_name(&new_page_name)?;
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let active_profile_key = crate::commands::config::get_active_profile_key(&db).unwrap_or_default();
    let conn = db.get_connection();

    conn.execute_batch("BEGIN IMMEDIATE TRANSACTION").map_err(|e| e.to_string())?;
    let result = if !active_profile_key.is_empty() {
        conn.execute(
            "UPDATE warehouse_items SET page_name = ?1 WHERE profile_key = ?2 AND page_name = ?3",
            params![validated_new_name, active_profile_key, validated_old_name],
        )
    } else {
        conn.execute(
            "UPDATE warehouse_items SET page_name = ?1 WHERE page_name = ?2",
            params![validated_new_name, validated_old_name],
        )
    };

    match result {
        Ok(_) => {
            conn.execute_batch("COMMIT").map_err(|e| e.to_string())?;
            Ok(())
        }
        Err(e) => {
            let _ = conn.execute_batch("ROLLBACK");
            Err(e.to_string())
        }
    }
}

#[tauri::command]
pub fn warehouse_delete_page(
    state: State<AppState>,
    page_name: String,
    delete_items: bool,
) -> Result<(), String> {
    if page_name.trim() == DEFAULT_WAREHOUSE_PAGE {
        return Err("默认收藏不可删除".to_string());
    }
    let validated_page_name = validate_page_name(&page_name)?;
    let db = state.db.lock().map_err(|e| e.to_string())?;
    let active_profile_key = crate::commands::config::get_active_profile_key(&db).unwrap_or_default();
    let conn = db.get_connection();

    conn.execute_batch("BEGIN IMMEDIATE TRANSACTION").map_err(|e| e.to_string())?;
    let result = if delete_items {
        if !active_profile_key.is_empty() {
            conn.execute(
                "DELETE FROM warehouse_items WHERE profile_key = ?1 AND page_name = ?2",
                params![active_profile_key, validated_page_name],
            )
        } else {
            conn.execute(
                "DELETE FROM warehouse_items WHERE page_name = ?1",
                params![validated_page_name],
            )
        }
    } else if !active_profile_key.is_empty() {
        conn.execute(
            "UPDATE warehouse_items SET page_name = ?1 WHERE profile_key = ?2 AND page_name = ?3",
            params![DEFAULT_WAREHOUSE_PAGE, active_profile_key, validated_page_name],
        )
    } else {
        conn.execute(
            "UPDATE warehouse_items SET page_name = ?1 WHERE page_name = ?2",
            params![DEFAULT_WAREHOUSE_PAGE, validated_page_name],
        )
    };

    match result {
        Ok(_) => {
            conn.execute_batch("COMMIT").map_err(|e| e.to_string())?;
            Ok(())
        }
        Err(e) => {
            let _ = conn.execute_batch("ROLLBACK");
            Err(e.to_string())
        }
    }
}

/// Normalize a raw item's mode/location/position for stash placement.
///
/// Overwrites mode → Stored, location → None, and px/py to the desired
/// stash grid position, while preserving the pg (page) field.
///
/// Bit layout (from item start):
///   bits 0-31:   flags (u32)
///   bits 32-34:  version (3 bits)
///   bits 35-37:  mode (3 bits) — overwritten to Stored(0)
///   bits 38-41:  location (4 bits) — overwritten to None(0)
///   bits 42-45:  px (4 bits) — set to position_x
///   bits 46-49:  py (4 bits) — set to position_y
///   bits 50-52:  pg (3 bits) — overwritten to SharedStash(6)
///   bits 53+:    Huffman code + body
///
/// For stackable stash items the game encodes quantity as `(py << 4) | px`;
/// for non-stackable items these are the grid position on the stash page.
fn update_item_position(raw_bits: &[u8], position_x: u8, position_y: u8, _new_amount: Option<u32>) -> Vec<u8> {
    use crate::protocol::d2i::legacy::{BitReader, BitWriter};

    // ★ Try to find the actual item start within raw_bits.
    // D2S-originated bits may have intra-byte padding (item starts at bit N%8).
    // Use try_parse_one to locate the true item header offset.
    let item_start_bit = {
        // Wrap raw_bits as JM data (prefix +64 byte zero header) for parse_jm_page
        let mut probe_buf = Vec::with_capacity(64 + raw_bits.len() + 4);
        probe_buf.extend_from_slice(&[0u8; 64]);
        probe_buf.extend_from_slice(b"JM");
        probe_buf.extend_from_slice(&[1u8, 0]); // count=1
        probe_buf.extend_from_slice(raw_bits);
        let parsed = crate::protocol::d2i::jm_reader::parse_jm_page(&probe_buf, 0, false);
        match parsed.first() {
            Some(pi) => {
                // item_start_bit = bit offset within raw_bits where the item header starts
                log::info!("[update_item_position] detected item_start_bit={} code={} x={} y={}",
                    pi.raw_bit_offset, pi.item.code, pi.item.x, pi.item.y);
                pi.raw_bit_offset
            }
            None => {
                log::warn!("[update_item_position] could not find item in raw_bits, assuming 0");
                0
            }
        }
    };

    let mut reader = BitReader::new(raw_bits);
    let mut writer = BitWriter::new(raw_bits.len() * 2);

    // Copy bits before item start unchanged (padding from extraction)
    for _ in 0..item_start_bit {
        if reader.remaining_bits() > 0 { writer.write_bit(reader.read_bit()); }
    }

    // Copy bits 0-34 unchanged (flags 32 + version 3)
    for _ in 0..35 {
        if reader.remaining_bits() > 0 { writer.write_bit(reader.read_bit()); }
    }

    // Write mode = Stored(0), 3 bits LSB-first
    for _ in 0..3 { writer.write_bit(0); }
    // Write location = None(0), 4 bits LSB-first
    for _ in 0..4 { writer.write_bit(0); }

    log::info!("[update_item_position] mode→Stored loc→None px={} py={} raw_bits={}B item_start_bit={}",
        position_x, position_y, raw_bits.len(), item_start_bit);

    // Write px (4 bits, LSB-first)
    for i in 0..4 {
        writer.write_bit((position_x >> i) & 1);
    }
    // Write py (4 bits, LSB-first)
    for i in 0..4 {
        writer.write_bit((position_y >> i) & 1);
    }

    // Write pg = MyStash(5), 3 bits LSB-first
    // ★ 游戏实际保存的共享仓库物品 pg=5（MyStash）——备份文件逐项验证过。
    //   写 6 会被游戏忽略（物品不显示）。Equipment items have pg=Equipped(0)
    //   which crashes D2R when placed in stash, 所以必须改写。
    for i in 0..3 { writer.write_bit((5u8 >> i) & 1); }

    // Skip old mode(3) + loc(4) + px(4) + py(4) + pg(3) = 18 bits in the reader
    for _ in 0..18 {
        reader.read_bit();
    }

    // Copy remaining bits unchanged
    while reader.remaining_bits() > 0 {
        writer.write_bit(reader.read_bit());
    }

    let result = writer.to_bytes();
    
    // Strip leading padding bytes (from item_start_bit offset) so the output
    // can be directly appended to JM data without shifting item alignment.
    let trim_bytes = item_start_bit / 8;
    let result = if trim_bytes > 0 && trim_bytes < result.len() {
        let mut trimmed = result[trim_bytes..].to_vec();
        // 补回 1 字节尾部填充（对齐测试文件）
        trimmed.push(0);
        log::info!("[update_item_position] stripped {} leading padding, padded trailing, output={}B", trim_bytes, trimmed.len());
        trimmed
    } else {
        result
    };
    log::info!("[update_item_position] output={}B", result.len());
    result
}


fn extract_item_bits(payload: &[u8], start_bit: usize, bit_len: usize) -> Result<Vec<u8>, String> {
    use crate::protocol::d2i::legacy::{BitReader, BitWriter};

    if start_bit + bit_len > payload.len() * 8 {
        return Err(format!(
            "Item bits out of range: start_bit={} bit_len={} payload_bits={}",
            start_bit,
            bit_len,
            payload.len() * 8
        ));
    }

    let mut reader = BitReader::new(payload);
    reader.seek(start_bit);

    let mut writer = BitWriter::new(bit_len + 8);
    for _ in 0..bit_len {
        if reader.remaining_bits() == 0 {
            return Err("Unexpected end of payload while extracting item bits".to_string());
        }
        writer.write_bit(reader.read_bit());
    }

    writer.align();
    Ok(writer.to_bytes())
}

/// Count actual items in a raw JM item bitstream.
fn count_items_in_jm_stream(data: &[u8]) -> usize {
    if data.is_empty() { return 0; }
    let mut buf = Vec::with_capacity(data.len() + 4);
    buf.extend_from_slice(b"JM");
    buf.extend_from_slice(&[0xFFu8, 0]);
    buf.extend_from_slice(data);
    let items = crate::protocol::d2i::parser::parse_item_stream_sequential(&buf, 0, false);
    log::info!("[withdraw] count_items_in_jm: {} items in {}B", items.len(), data.len());
    items.len()
}

fn restore_stash_from_backup(stash_path: &str, backup_path: &std::path::Path) -> Result<(), String> {
    std::fs::copy(backup_path, stash_path)
        .map(|_| ())
        .map_err(|e| format!("Failed to restore stash from backup: {}", e))
}


/// Deposit a stash item into the extended warehouse.
/// Deducts the item from the game stash and stores it in the database.
